// #pragma once

#ifndef ROBOT_HAL_H
#define ROBOT_HAL_H

#include "robo/hal/telemetry.h"

namespace robo {
// Уровень абстрактной аппаратной абстракции.
//
// Реализации:
//   - UdpDiffHAL — симулятор веб-роботов через UDP/TCP.
//   - McuHAL (будущее) — реальное оборудование через UART/CAN/периферийные устройства.
//
// Контракт:
//   Оба метода НЕБЛОКИРУЮЩИЕ. Вызывающий абонент выполняет жесткий цикл управления и
//   никогда не должен останавливаться из-за задержки передачи.

// Обстрактный базовый класс(интерфейс), описывает, что должен уметь робот. 
class RobotHAL {
public:
    RobotHAL() noexcept = default; // Конструктор по умолчанию
    virtual ~RobotHAL() = default; // Виртуальный деструктор

    // Запрет, объект нельзя копировать и перемещать.
    RobotHAL(const RobotHAL&)            = delete;
    RobotHAL& operator=(const RobotHAL&) = delete;
    RobotHAL(RobotHAL&&)                 = delete;
    RobotHAL& operator=(RobotHAL&&)      = delete;

    // Виртуальные функции: наследник обязан их реализовать

    // Отправить команду velocity.
    // Возвращает значение false при сбое передачи (сокет закрыт, буфер заполнен, ...).
    virtual bool send_velocity(float linear_x, float angular_z) noexcept = 0;

    // Запросить новый кадр телеметрии.
    // Возвращает значение true, если был обработан полный новый кадр.
    // Кадр "out" действителен до следующего вызова функции poll_telemetry().
    virtual bool poll_telemetry(Telemetry& out) noexcept = 0;
};

/*
HAL (Hardware Abstraction Layer).
    HAL управляет реальным железом: сокетами, портами, потоками. Копирование такого объекта — бессмыслица.
    Что значит «две копии одного соединения»? Кто закрывает сокет? Кто владеет потоком?
    Такие объекты должны существовать в единственном экземпляре. Копирование запрещено,
    чтобы никто случайно не сделал дубль и не получил двойное закрытие сокета или гонку.
*/

} // namespace robo

#endif // ROBOT_HAL_H
